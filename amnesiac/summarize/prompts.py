"""Prompt packs and rendering helpers for summarization."""

from collections.abc import Mapping, Sequence
from typing import Any

from pydantic import BaseModel, ConfigDict

from amnesiac.exceptions import PromptRenderError
from amnesiac.types import Doc


class PromptPack(BaseModel):
    """An immutable collection of templates used by both summarization stages."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str
    axis_system: str
    axis_user: str
    meta_system: str
    meta_user: str
    doc_template: str = "[день {day_number} | {channel}] {text}"
    doc_separator: str = "\n"
    axis_block_template: str = "=== Ось: {axis} ===\n\n{summary}"
    axis_block_separator: str = "\n\n"
    params: Mapping[str, Any] = {}

    def bind(self, **kwargs: Any) -> "PromptPack":
        """Return a new pack with additional template parameters bound."""
        return self.model_copy(update={"params": {**self.params, **kwargs}})

    def _render(self, template_name: str, **runtime: Any) -> str:
        template = getattr(self, template_name)
        values = {**self.params, **runtime}
        try:
            return template.format(**values)
        except KeyError as exc:
            missing_key = exc.args[0]
            raise PromptRenderError(
                f"Could not render {template_name}: missing key {missing_key!r}"
            ) from exc

    def _render_docs(self, docs: Sequence[Doc]) -> str:
        return self.doc_separator.join(
            self._render(
                "doc_template",
                day_number=doc.day_number,
                channel=doc.channel,
                text=doc.text,
            )
            for doc in docs
        )

    def _render_axis_blocks(self, axis_summaries: Mapping[str, str]) -> str:
        return self.axis_block_separator.join(
            self._render("axis_block_template", axis=axis, summary=summary)
            for axis, summary in axis_summaries.items()
        )

    def _render_axis_system(self, *, axis: str) -> str:
        return self._render("axis_system", axis=axis)

    def _render_axis_user(self, *, axis: str, docs: str) -> str:
        return self._render("axis_user", axis=axis, docs=docs)

    def _render_meta_system(self) -> str:
        return self._render("meta_system")

    def _render_meta_user(self, *, axis_blocks: str) -> str:
        return self._render("meta_user", axis_blocks=axis_blocks)


